"""Runs spec/conformance.json against this (the reference) implementation.

The expected values in that file are generated by ``spec/generate_conformance.py`` and shared with the
JavaScript and PHP packages. If one of these tests fails you changed the behaviour defined in SPEC.md:
change SPEC.md and every other implementation too, then regenerate the file.
"""
import json
import pathlib

import pytest

import cambodia_geo as kh

SPEC_FILE = pathlib.Path(__file__).resolve().parent.parent / "spec" / "conformance.json"
pytestmark = pytest.mark.skipif(not SPEC_FILE.exists(), reason="spec/ is not available (installed package)")

DATA = json.loads(SPEC_FILE.read_text(encoding="utf-8")) if SPEC_FILE.exists() else {"cases": []}
LEVEL = {kh.Province: "province", kh.District: "district", kh.Commune: "commune", kh.Village: "village"}
FUNCS = {
    "provinces": kh.provinces,
    "districts": kh.districts,
    "communes": kh.communes,
    "villages": kh.villages,
    "get_province": kh.get_province,
    "get_district": kh.get_district,
    "get_commune": kh.get_commune,
    "get_village": kh.get_village,
    "search": kh.search,
}


def plain(value, with_level):
    if value is None:
        return None
    if isinstance(value, list):
        return [plain(v, with_level) for v in value]
    d = value.to_dict()
    return {"level": LEVEL[type(value)], **d} if with_level else d


def test_generated_for_the_same_data_year():
    assert DATA["data_year"] == kh.DATA_YEAR


@pytest.mark.parametrize(
    "case",
    DATA["cases"],
    ids=lambda c: f"{c['fn']}({json.dumps(c['args'], ensure_ascii=False)}, {json.dumps(c['kwargs'], ensure_ascii=False)})",
)
def test_case(case):
    call = FUNCS[case["fn"]]
    if case.get("raises"):
        with pytest.raises(ValueError):
            call(*case["args"], **case["kwargs"])
        return
    actual = plain(call(*case["args"], **case["kwargs"]), case["fn"] == "search")
    if "expect_len" in case:
        assert len(actual) == case["expect_len"]
    else:
        assert actual == case["expect"]
